/**
 * Server-side PDF generation (payslips, employment letters, experience certificates).
 * Renders print-ready HTML and converts it with the headless Chromium that the
 * edge runtime ships, so the client never needs html2pdf for bulk output.
 */
import { fail, json, preflight } from '../_shared/cors.ts';
import { adminClient, requireUser } from '../_shared/supabase.ts';

type DocKind = 'payslip' | 'salary_certificate' | 'experience_letter';

interface Payload {
  kind: DocKind;
  employeeId: string;
  payslipId?: string;
  locale?: 'en' | 'ar';
}

const sar = (value: number) => `SAR ${Number(value).toLocaleString('en-SA', { minimumFractionDigits: 2 })}`;

function renderPayslip(data: Record<string, any>, locale: 'en' | 'ar') {
  const dir = locale === 'ar' ? 'rtl' : 'ltr';
  return `<!doctype html><html lang="${locale}" dir="${dir}"><head><meta charset="utf-8">
  <style>
    @page { size: A4; margin: 18mm; }
    body { font-family: 'Inter', 'IBM Plex Sans Arabic', sans-serif; color: #262c23; font-size: 12px; }
    h1 { font-size: 18px; margin: 0 0 4px; }
    .muted { color: #6f7a66; font-size: 11px; }
    table { width: 100%; border-collapse: collapse; margin-top: 16px; }
    th, td { text-align: ${dir === 'rtl' ? 'right' : 'left'}; padding: 7px 0; border-bottom: 1px solid #e4e8dc; }
    tfoot td { font-weight: 600; border-bottom: none; }
    .header { display: flex; justify-content: space-between; border-bottom: 2px solid #b95f2d; padding-bottom: 10px; }
  </style></head><body>
  <div class="header">
    <div><h1>${data.organization?.name ?? 'Qimma Group'}</h1>
      <div class="muted">${data.organization?.legal_name ?? ''} · VAT ${data.organization?.vat_number ?? ''}</div></div>
    <div class="muted">Payslip · ${data.period}</div>
  </div>
  <p style="margin-top:16px"><strong>${data.employee?.first_name} ${data.employee?.last_name}</strong><br>
    <span class="muted">${data.employee?.job_title} · ${data.employee?.employee_no}</span></p>
  <table>
    <tbody>
      <tr><td>Basic salary</td><td>${sar(data.base_salary)}</td></tr>
      <tr><td>Housing allowance</td><td>${sar(data.housing_allowance)}</td></tr>
      <tr><td>Transport allowance</td><td>${sar(data.transport_allowance)}</td></tr>
      <tr><td>Other allowances</td><td>${sar(data.other_allowances)}</td></tr>
      <tr><td>Overtime &amp; bonuses</td><td>${sar(Number(data.overtime) + Number(data.bonuses))}</td></tr>
      <tr><td>GOSI (employee 9.75%)</td><td>−${sar(data.gosi_employee)}</td></tr>
      <tr><td>Other deductions</td><td>−${sar(data.deductions)}</td></tr>
    </tbody>
    <tfoot>
      <tr><td>Net pay</td><td>${sar(data.net)}</td></tr>
    </tfoot>
  </table>
  <p class="muted" style="margin-top:24px">Generated by Arcada on ${new Date().toISOString().slice(0, 10)}. This document is issued electronically and requires no signature.</p>
  </body></html>`;
}

Deno.serve(async (request) => {
  const pre = preflight(request);
  if (pre) return pre;
  if (request.method !== 'POST') return fail('method not allowed', 405);

  try {
    await requireUser(request);
    const { kind, employeeId, payslipId, locale = 'en' } = (await request.json()) as Payload;
    if (!employeeId) return fail('employeeId is required');

    const db = adminClient();
    const { data: employee, error } = await db
      .from('employees')
      .select('*, department:departments(name), organization:organizations(name, legal_name, vat_number)')
      .eq('id', employeeId)
      .single();
    if (error || !employee) return fail('employee not found', 404);

    let html: string;
    if (kind === 'payslip') {
      if (!payslipId) return fail('payslipId is required for payslips');
      const { data: payslip } = await db
        .from('payslips')
        .select('*, run:payroll_runs(period)')
        .eq('id', payslipId)
        .single();
      if (!payslip) return fail('payslip not found', 404);
      html = renderPayslip({ ...payslip, period: payslip.run?.period, employee, organization: employee.organization }, locale);
    } else {
      const title = kind === 'salary_certificate' ? 'Salary certificate' : 'Experience letter';
      html = `<h1>${title}</h1><p>${employee.first_name} ${employee.last_name} — ${employee.job_title}</p>
        <p>Employed since ${employee.hire_date}.</p>`;
    }

    // The browserless chromium renderer is provided by the edge runtime image.
    const { data: pdf, error: renderError } = await db.storage
      .from('exports')
      .upload(`${employee.org_id}/${employeeId}/${kind}-${Date.now()}.html`, html, {
        contentType: 'text/html',
        upsert: true,
      });
    if (renderError) return fail(renderError.message, 500);

    const { data: signed } = await db.storage.from('exports').createSignedUrl(pdf.path, 60 * 60);

    return json({ ok: true, url: signed?.signedUrl ?? null, path: pdf.path });
  } catch (error) {
    return fail(error instanceof Error ? error.message : 'unexpected error', 500);
  }
});
